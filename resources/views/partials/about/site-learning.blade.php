    <h3>Learning in Public</h3>
    <p>
        I decided to let my learning process be public. 
        I made the project open source from its beginning, created a project board and document everything both for myself and for others, 
        whether they want to take a peek or contribute.
        This approach helped me stay accountable, reflect on what I was learning, and invite others to follow along.
    </p>

    <p>
        I clearly remember starting out, learning about GitHub, conventional commits, etc. 
        I'm still learning and I am far from perfect but really, who and what is?
        Everything and everyone is evolving. So why keep the current version a secret? 
    </p>

    <p>
        Well, that's great to say but, it's just words. 
        Have I really learned to feel exposed? To a level. 
        Could I step it up? Of course I could. 
        Could I do something for others as well? Of course.
    </p>

    <p>
        Getting this website open and deployed from the first moments helped despite the anxiety of the unknown.
    </p>

    <p>
        Sharing my progress openly allows me to connect with others, receive feedback, and see different perspectives.
        It's both a learning method and a way to give back to the community.
    </p>
